import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, before, describe, it } from "node:test";
import { fileURLToPath } from "node:url";

const SCRIPT = path.join(path.dirname(fileURLToPath(import.meta.url)), "find-transcript.mjs");

let root;
let config;
let cwd;
let projectDir;
let clock = Date.now() / 1000 - 1000;

before(() => {
	root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "find-transcript-")));
	config = path.join(root, "config");
	cwd = path.join(root, "work", "my_repo.v2");
	fs.mkdirSync(cwd, { recursive: true });
	projectDir = path.join(config, "projects", cwd.replace(/[^a-zA-Z0-9]/g, "-"));
	fs.mkdirSync(projectDir, { recursive: true });
});
after(() => fs.rmSync(root, { recursive: true, force: true }));

// Each fixture gets a later mtime than the last, so "newest" is deterministic.
function transcript(name, records, dir = projectDir) {
	const file = path.join(dir, `${name}.jsonl`);
	fs.mkdirSync(dir, { recursive: true });
	const header = [
		{ type: "permission-mode", permissionMode: "default", sessionId: name },
		{ type: "file-history-snapshot", snapshot: {} },
	];
	fs.writeFileSync(file, [...header, ...records].map((r) => JSON.stringify(r)).join("\n") + "\n");
	clock += 10;
	fs.utimesSync(file, clock, clock);
	return file;
}
const user = (content, extra = {}) => ({ type: "user", isSidechain: false, cwd, message: { role: "user", content }, ...extra });
const assistant = (text) => ({ type: "assistant", message: { role: "assistant", content: [{ type: "text", text }] } });
const toolResult = (text) => user([{ type: "tool_result", tool_use_id: "t1", content: text }]);
const CAVEAT = user(
	"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>",
	{ isMeta: true },
);

function find(args, env = { CLAUDE_CONFIG_DIR: config }) {
	const result = spawnSync(process.execPath, [SCRIPT, ...args], {
		cwd,
		env: { ...process.env, ...env },
		encoding: "utf8",
	});
	return { code: result.status, stdout: result.stdout.trim(), stderr: result.stderr };
}

describe("find-transcript", () => {
	it("prefers a session that opens with the fragment over a newer one that only quotes it", () => {
		const target = transcript("feature-session", [user("Product wants a zebra filter on the feed. Build it.")]);
		const quoting = transcript("reflect-session", [user("reflect on the session that started 'Product wants a zebra filter on the feed'")]);
		assert.equal(find(["Product wants a zebra filter"]).stdout, target);
		assert.equal(find(["started 'product wants a zebra"]).stdout, quoting, "a contains-only match is still found");
		assert.equal(find(["--exclude", "feature-session", "Product wants a zebra filter"]).stdout, quoting, "--exclude drops a session id");
	});

	it("finds a plain opening prompt, case- and whitespace-insensitively", () => {
		const file = transcript("plain", [user("Please  refactor the\nBilling   module"), assistant("ok"), user("and add tests")]);
		assert.deepEqual(find(["refactor the billing module"]), { code: 0, stdout: file, stderr: "" });
		assert.equal(find(["and add tests"]).code, 1, "only the opening prompt counts");
	});

	it("skips a /clear and its local-command markup", () => {
		const file = transcript("clear-first", [
			CAVEAT,
			user("<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>"),
			user("<local-command-stdout></local-command-stdout>"),
			user("migrate the queue worker to tokio"),
		]);
		assert.equal(find(["migrate the queue worker"]).stdout, file);
	});

	it("matches a skill slash command on its arguments", () => {
		const file = transcript("skill-first", [
			user("<command-message>auto is running…</command-message>\n<command-name>/auto</command-name>\n<command-args>ship the onboarding flow</command-args>"),
			user([{ type: "text", text: "Base directory for this skill: /x\n\n# Auto" }], { isMeta: true }),
			assistant("on it"),
			user("also fix lint"),
		]);
		assert.equal(find(["ship the onboarding flow"]).stdout, file);
		assert.equal(find(["also fix lint"]).code, 1);
	});

	it("does not take a built-in command's arguments as the prompt", () => {
		const file = transcript("builtin-args", [
			CAVEAT,
			user("<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>"),
			user("<local-command-stdout>Set model to opus</local-command-stdout>"),
			user("profile the slow import"),
		]);
		assert.equal(find(["profile the slow import"]).stdout, file);
	});

	it("skips a `!` bash command and its output", () => {
		const file = transcript("bash-first", [
			CAVEAT,
			user("<bash-input>git status</bash-input>"),
			user("<bash-stdout>On branch main</bash-stdout><bash-stderr></bash-stderr>"),
			user("why is the tree dirty"),
		]);
		assert.equal(find(["why is the tree dirty"]).stdout, file);
	});

	it("skips isMeta records, tool results, and compaction summaries", () => {
		const file = transcript("meta-first", [
			user("<system-reminder>context</system-reminder> rename the widget", { isMeta: true }),
			user("This session is being continued from a previous conversation. rename the widget", {
				isCompactSummary: true,
				isVisibleInTranscriptOnly: true,
			}),
			toolResult("rename the widget"),
			user([{ type: "text", text: "Port the gadget" }, { type: "image", source: {} }]),
		]);
		assert.equal(find(["port the gadget"]).stdout, file);
		assert.notEqual(find(["rename the widget"]).stdout, file);
	});

	it("prefers the newest matching session", () => {
		transcript("older", [user("bump the shared dependency")]);
		const newer = transcript("newer", [user("Bump the shared dependency again")]);
		assert.equal(find(["bump the shared dependency"]).stdout, newer);
	});

	it("ignores subagent transcripts", () => {
		transcript("agent-abc", [user("audit the subagent path", { isSidechain: true })]);
		transcript("agent-1", [user("audit the subagent path", { isSidechain: true })], path.join(projectDir, "session", "subagents"));
		transcript("sidechain", [user("audit the subagent path", { isSidechain: true })]);
		assert.equal(find(["audit the subagent path"]).code, 1);
	});

	it("exits 1 with a message when nothing matches", () => {
		const result = find(["no session ever said this"]);
		assert.equal(result.code, 1);
		assert.equal(result.stdout, "");
		assert.match(result.stderr, /no session in .* opens with a prompt containing "no session ever said this"/);
	});

	it("respects CLAUDE_CONFIG_DIR and --cwd", () => {
		const other = path.join(root, "other");
		const otherCwd = path.join(root, "elsewhere");
		fs.mkdirSync(otherCwd);
		const file = transcript(
			"other-config",
			[user("only in the other config")],
			path.join(other, "projects", otherCwd.replace(/[^a-zA-Z0-9]/g, "-")),
		);
		assert.equal(find(["--cwd", otherCwd, "only in the other config"], { CLAUDE_CONFIG_DIR: other }).stdout, file);
		assert.equal(find(["--cwd", otherCwd, "only in the other config"]).code, 1, "default config has no such project");
		assert.equal(find(["only in the other config"], { CLAUDE_CONFIG_DIR: other }).code, 1, "cwd scopes the search");
	});
});
